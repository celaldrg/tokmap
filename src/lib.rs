//! tokmap: see where a repository's tokens go before an AI agent reads it.

pub mod estimate;

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

pub use estimate::estimate_tokens;

/// Directories skipped when the target is not a git repository.
const DEFAULT_SKIP_DIRS: &[&str] = &[
    ".git",
    "node_modules",
    "target",
    "dist",
    "build",
    ".venv",
    "venv",
    "__pycache__",
    ".next",
    ".cache",
    "vendor",
    ".idea",
    ".vscode",
];

const LOCKFILES: &[&str] = &[
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "bun.lock",
    "Cargo.lock",
    "poetry.lock",
    "uv.lock",
    "Pipfile.lock",
    "composer.lock",
    "Gemfile.lock",
    "go.sum",
    "flake.lock",
    "packages.lock.json",
];

/// Why a file is probably not worth an agent's context.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Hint {
    Lockfile,
    Minified,
    Generated,
    Snapshot,
    Huge,
}

impl Hint {
    pub fn as_str(self) -> &'static str {
        match self {
            Hint::Lockfile => "lockfile",
            Hint::Minified => "minified",
            Hint::Generated => "generated",
            Hint::Snapshot => "test snapshot",
            Hint::Huge => "very large file",
        }
    }
}

#[derive(Debug, Clone)]
pub struct FileStat {
    /// Path relative to the scanned root, with `/` separators.
    pub path: String,
    pub bytes: u64,
    pub lines: u64,
    pub tokens: u64,
    pub hint: Option<Hint>,
}

#[derive(Debug, Default)]
pub struct Scan {
    pub files: Vec<FileStat>,
    pub skipped_binary: u64,
    pub used_git: bool,
}

impl Scan {
    pub fn total_tokens(&self) -> u64 {
        self.files.iter().map(|f| f.tokens).sum()
    }
}

/// Classify a file from its path and contents.
pub fn classify(path: &str, text: &str, tokens: u64) -> Option<Hint> {
    let name = path.rsplit('/').next().unwrap_or(path);
    if LOCKFILES.contains(&name) {
        return Some(Hint::Lockfile);
    }
    if name.ends_with(".snap") || path.contains("__snapshots__/") {
        return Some(Hint::Snapshot);
    }
    if name.contains(".min.") || name.ends_with(".map") {
        return Some(Hint::Minified);
    }
    let head: String = text.chars().take(600).collect::<String>().to_lowercase();
    if head.contains("@generated")
        || head.contains("do not edit")
        || head.contains("code generated by")
        || name.ends_with(".pb.go")
        || name.ends_with("_pb2.py")
    {
        return Some(Hint::Generated);
    }
    let lines = text.lines().count().max(1);
    if text.len() > 2000 && text.len() / lines > 300 {
        return Some(Hint::Minified);
    }
    if tokens > 50_000 {
        return Some(Hint::Huge);
    }
    None
}

fn is_binary(bytes: &[u8]) -> bool {
    bytes.iter().take(8000).any(|&b| b == 0)
}

/// Measure one file's contents.
pub fn measure(path: String, bytes: &[u8]) -> Option<FileStat> {
    if is_binary(bytes) {
        return None;
    }
    let text = String::from_utf8_lossy(bytes);
    let tokens = estimate_tokens(&text);
    let hint = classify(&path, &text, tokens);
    Some(FileStat {
        lines: text.lines().count() as u64,
        bytes: bytes.len() as u64,
        tokens,
        hint,
        path,
    })
}

fn git_files(root: &Path) -> Option<Vec<String>> {
    let out = Command::new("git")
        .arg("-C")
        .arg(root)
        .args([
            "ls-files",
            "-z",
            "--cached",
            "--others",
            "--exclude-standard",
        ])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let s = String::from_utf8_lossy(&out.stdout);
    Some(
        s.split('\0')
            .filter(|p| !p.is_empty())
            .map(String::from)
            .collect(),
    )
}

fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let mut entries: Vec<_> = entries.flatten().collect();
    entries.sort_by_key(|e| e.file_name());
    for e in entries {
        let p = e.path();
        let Ok(ft) = e.file_type() else { continue };
        if ft.is_dir() {
            let name = e.file_name();
            if DEFAULT_SKIP_DIRS.contains(&name.to_string_lossy().as_ref()) {
                continue;
            }
            walk(root, &p, out);
        } else if ft.is_file() {
            if let Ok(rel) = p.strip_prefix(root) {
                out.push(rel.to_string_lossy().replace('\\', "/"));
            }
        }
    }
}

/// Scan `root`. Inside a git repository the file list comes from git, so
/// `.gitignore` is respected; otherwise common build and dependency folders
/// are skipped.
pub fn scan(root: &Path, use_git: bool) -> std::io::Result<Scan> {
    let mut scan = Scan::default();
    if root.is_file() {
        let bytes = fs::read(root)?;
        let name = root
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default();
        match measure(name, &bytes) {
            Some(f) => scan.files.push(f),
            None => scan.skipped_binary += 1,
        }
        return Ok(scan);
    }
    let list = if use_git { git_files(root) } else { None };
    scan.used_git = list.is_some();
    let list = list.unwrap_or_else(|| {
        let mut v = Vec::new();
        walk(root, root, &mut v);
        v
    });
    for rel in list {
        let full: PathBuf = root.join(&rel);
        let Ok(bytes) = fs::read(&full) else { continue };
        match measure(rel, &bytes) {
            Some(f) => scan.files.push(f),
            None => scan.skipped_binary += 1,
        }
    }
    Ok(scan)
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Group {
    pub name: String,
    pub tokens: u64,
    pub files: u64,
    pub is_dir: bool,
}

/// Group files by their first `depth` path components.
pub fn group(files: &[FileStat], depth: usize) -> Vec<Group> {
    let depth = depth.max(1);
    let mut map: BTreeMap<(String, bool), (u64, u64)> = BTreeMap::new();
    for f in files {
        let parts: Vec<&str> = f.path.split('/').collect();
        let (key, is_dir) = if parts.len() > depth {
            (format!("{}/", parts[..depth].join("/")), true)
        } else {
            (f.path.clone(), false)
        };
        let e = map.entry((key, is_dir)).or_insert((0, 0));
        e.0 += f.tokens;
        e.1 += 1;
    }
    let mut groups: Vec<Group> = map
        .into_iter()
        .map(|((name, is_dir), (tokens, files))| Group {
            name,
            tokens,
            files,
            is_dir,
        })
        .collect();
    groups.sort_by(|a, b| b.tokens.cmp(&a.tokens).then(a.name.cmp(&b.name)));
    groups
}

/// `1234567` -> `1,234,567`
pub fn thousands(n: u64) -> String {
    let digits: Vec<char> = n.to_string().chars().rev().collect();
    let groups: Vec<String> = digits
        .chunks(3)
        .map(|c| c.iter().rev().collect())
        .rev()
        .collect();
    groups.join(",")
}

fn bar(share: f64, width: usize) -> String {
    let filled = (share * width as f64).round() as usize;
    let filled = filled.min(width);
    format!("{}{}", "█".repeat(filled), "░".repeat(width - filled))
}

pub struct ReportOptions {
    pub label: String,
    pub depth: usize,
    pub top: usize,
    pub budget: Option<u64>,
}

/// Human-readable report.
pub fn render_text(scan: &Scan, opts: &ReportOptions) -> String {
    let total = scan.total_tokens();
    let mut out = String::new();
    out.push_str(&format!(
        "tokmap  {}  ~{} tokens in {} files",
        opts.label,
        thousands(total),
        scan.files.len()
    ));
    if let Some(b) = opts.budget {
        let pct = if b == 0 {
            0.0
        } else {
            total as f64 * 100.0 / b as f64
        };
        out.push_str(&format!("  ({:.0}% of a {} budget)", pct, thousands(b)));
    }
    out.push('\n');
    if scan.skipped_binary > 0 {
        out.push_str(&format!(
            "        {} binary files skipped\n",
            scan.skipped_binary
        ));
    }
    out.push('\n');

    let groups = group(&scan.files, opts.depth);
    let shown = groups.len().min(opts.top);
    for g in &groups[..shown] {
        let share = if total == 0 {
            0.0
        } else {
            g.tokens as f64 / total as f64
        };
        let files = if g.is_dir {
            format!(
                "  ({} {})",
                g.files,
                if g.files == 1 { "file" } else { "files" }
            )
        } else {
            String::new()
        };
        out.push_str(&format!(
            "  {:>5.1}%  {:>9}  {}  {}{}\n",
            share * 100.0,
            thousands(g.tokens),
            bar(share, 20),
            g.name,
            files
        ));
    }
    if groups.len() > shown {
        let rest: u64 = groups[shown..].iter().map(|g| g.tokens).sum();
        out.push_str(&format!(
            "                       …and {} more entries, {} tokens\n",
            groups.len() - shown,
            thousands(rest)
        ));
    }

    let mut hinted: Vec<&FileStat> = scan.files.iter().filter(|f| f.hint.is_some()).collect();
    hinted.sort_by_key(|f| std::cmp::Reverse(f.tokens));
    if !hinted.is_empty() {
        let saved: u64 = hinted.iter().map(|f| f.tokens).sum();
        out.push_str(&format!(
            "\nProbably not worth an agent's context (~{} tokens, {:.0}%):\n",
            thousands(saved),
            if total == 0 {
                0.0
            } else {
                saved as f64 * 100.0 / total as f64
            }
        ));
        for f in hinted.iter().take(opts.top) {
            out.push_str(&format!(
                "  {:>9}  {}  [{}]\n",
                thousands(f.tokens),
                f.path,
                f.hint.unwrap().as_str()
            ));
        }
        out.push_str("  Tip: list them in your agent's ignore file (for example .cursorignore or .aiderignore).\n");
    }
    out
}

fn json_str(s: &str) -> String {
    let mut o = String::with_capacity(s.len() + 2);
    o.push('"');
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c if (c as u32) < 0x20 => o.push_str(&format!("\\u{:04x}", c as u32)),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// Machine-readable report.
pub fn render_json(scan: &Scan, opts: &ReportOptions) -> String {
    let mut files: Vec<&FileStat> = scan.files.iter().collect();
    files.sort_by(|a, b| b.tokens.cmp(&a.tokens).then(a.path.cmp(&b.path)));
    let items: Vec<String> = files
        .iter()
        .map(|f| {
            format!(
                "{{\"path\":{},\"tokens\":{},\"bytes\":{},\"lines\":{},\"hint\":{}}}",
                json_str(&f.path),
                f.tokens,
                f.bytes,
                f.lines,
                f.hint
                    .map(|h| json_str(h.as_str()))
                    .unwrap_or_else(|| "null".into())
            )
        })
        .collect();
    let groups: Vec<String> = group(&scan.files, opts.depth)
        .iter()
        .map(|g| {
            format!(
                "{{\"name\":{},\"tokens\":{},\"files\":{},\"dir\":{}}}",
                json_str(&g.name),
                g.tokens,
                g.files,
                g.is_dir
            )
        })
        .collect();
    format!(
        "{{\"root\":{},\"total_tokens\":{},\"files_count\":{},\"skipped_binary\":{},\"budget\":{},\"groups\":[{}],\"files\":[{}]}}\n",
        json_str(&opts.label),
        scan.total_tokens(),
        scan.files.len(),
        scan.skipped_binary,
        opts.budget.map(|b| b.to_string()).unwrap_or_else(|| "null".into()),
        groups.join(","),
        items.join(",")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn f(path: &str, tokens: u64) -> FileStat {
        FileStat {
            path: path.into(),
            bytes: 0,
            lines: 0,
            tokens,
            hint: None,
        }
    }

    #[test]
    fn groups_by_depth() {
        let files = vec![f("src/a.rs", 10), f("src/b/c.rs", 5), f("README.md", 3)];
        let g = group(&files, 1);
        assert_eq!(
            g[0],
            Group {
                name: "src/".into(),
                tokens: 15,
                files: 2,
                is_dir: true
            }
        );
        assert_eq!(g[1].name, "README.md");
        let g2 = group(&files, 2);
        assert!(g2.iter().any(|x| x.name == "src/b/" && x.tokens == 5));
        assert!(g2.iter().any(|x| x.name == "src/a.rs" && !x.is_dir));
    }

    #[test]
    fn formats_thousands() {
        assert_eq!(thousands(0), "0");
        assert_eq!(thousands(999), "999");
        assert_eq!(thousands(1000), "1,000");
        assert_eq!(thousands(1234567), "1,234,567");
    }

    #[test]
    fn classifies_common_noise() {
        assert_eq!(
            classify("web/package-lock.json", "{}", 1),
            Some(Hint::Lockfile)
        );
        assert_eq!(classify("a/app.min.js", "x", 1), Some(Hint::Minified));
        assert_eq!(
            classify("x.go", "// Code generated by protoc. DO NOT EDIT.\n", 1),
            Some(Hint::Generated)
        );
        assert_eq!(
            classify("t/__snapshots__/a.snap", "", 1),
            Some(Hint::Snapshot)
        );
        let long_line = "a".repeat(5000);
        assert_eq!(classify("bundle.js", &long_line, 10), Some(Hint::Minified));
        assert_eq!(classify("src/main.rs", "fn main() {}\n", 4), None);
    }

    #[test]
    fn binary_files_are_skipped() {
        assert!(measure("x.png".into(), &[0x89, b'P', 0, 1]).is_none());
        assert!(measure("x.txt".into(), b"hello").is_some());
    }

    #[test]
    fn json_escapes() {
        assert_eq!(json_str("a\"b\\c\n"), "\"a\\\"b\\\\c\\n\"");
    }
}
